def fibonacci(n):  
    a, b = 0, 1  
    for _ in range(n):  
        yield a  
        a, b = b, a + b  
fib_sequence = list(fibonacci(10))  
print(fib_sequence)  
sum_fib = sum(fib_sequence)  
print("Sum:", sum_fib)  
max_fib = max(fib_sequence)
